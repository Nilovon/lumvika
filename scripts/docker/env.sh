# Sourced by the app, migrate, Postgres and RustFS containers of docker-compose.yml before they start.
# Fills every secret .env left empty with the one generated for this install (init-secrets.sh), then
# derives the values built from them. Copied into the `secrets` volume on every start, so an update of
# the image updates it too.

. /run/lumvika/generated.env

: "${POSTGRES_PASSWORD:=$GENERATED_POSTGRES_PASSWORD}"
: "${BETTER_AUTH_SECRET:=$GENERATED_BETTER_AUTH_SECRET}"
: "${LUMVIKA_ENGINE_API_KEY:=$GENERATED_LUMVIKA_ENGINE_API_KEY}"
: "${STEWARD_HUB_TOKEN_SECRET:=$GENERATED_STEWARD_HUB_TOKEN_SECRET}"
: "${BOARD_IMAGE_SECRET:=$GENERATED_BOARD_IMAGE_SECRET}"
: "${UNSUBSCRIBE_SECRET:=$GENERATED_UNSUBSCRIBE_SECRET}"
: "${PUBLISHED_ACCESS_SECRET:=$GENERATED_PUBLISHED_ACCESS_SECRET}"
: "${MOBILE_OAUTH_TICKET_SECRET:=$GENERATED_MOBILE_OAUTH_TICKET_SECRET}"
: "${S3_ACCESS_KEY_ID:=lumvika}"
: "${S3_SECRET_ACCESS_KEY:=$GENERATED_S3_SECRET_ACCESS_KEY}"

: "${DATABASE_URL:=postgres://lumvika:${POSTGRES_PASSWORD}@postgres:5432/lumvika}"
: "${RUSTFS_ACCESS_KEY:=$S3_ACCESS_KEY_ID}"
: "${RUSTFS_SECRET_KEY:=$S3_SECRET_ACCESS_KEY}"

export POSTGRES_PASSWORD BETTER_AUTH_SECRET LUMVIKA_ENGINE_API_KEY STEWARD_HUB_TOKEN_SECRET \
    BOARD_IMAGE_SECRET UNSUBSCRIBE_SECRET PUBLISHED_ACCESS_SECRET MOBILE_OAUTH_TICKET_SECRET \
    S3_ACCESS_KEY_ID S3_SECRET_ACCESS_KEY DATABASE_URL RUSTFS_ACCESS_KEY RUSTFS_SECRET_KEY

unset GENERATED_POSTGRES_PASSWORD GENERATED_BETTER_AUTH_SECRET GENERATED_LUMVIKA_ENGINE_API_KEY \
    GENERATED_STEWARD_HUB_TOKEN_SECRET GENERATED_BOARD_IMAGE_SECRET GENERATED_UNSUBSCRIBE_SECRET \
    GENERATED_PUBLISHED_ACCESS_SECRET GENERATED_MOBILE_OAUTH_TICKET_SECRET GENERATED_S3_SECRET_ACCESS_KEY
